# Implementasi Operator di Python
a = 15
b = 4

# 1. Operator Aritmatika
print("Penjumlahan:", a + b)
print("Pengurangan:", a - b)
print("Perkalian:", a * b)
print("Pembagian:", a / b)
print("Sisa Bagi (Modulus):", a % b)

# 2. Operator Perbandingan
print("Apakah a > b?:", a > b)
print("Apakah a == b?:", a == b)

# 3. Operator Logika
kondisi_1 = True
kondisi_2 = False
print("Logika AND:", kondisi_1 and kondisi_2)
print("Logika OR:", kondisi_1 or kondisi_2)