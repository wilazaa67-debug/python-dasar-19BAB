# Implementasi Konstanta di Python (menggunakan konvensi huruf kapital)
PI = 3.14159
NAMA_SEKOLAH = "SMKN 2 Subang"
JURUSAN = "Rekayasa Perangkat Lunak"

jari_jari = 7
luas_lingkaran = PI * (jari_jari ** 2)

print("Sekolah:", NAMA_SEKOLAH)
print("Jurusan:", JURUSAN)
print(f"Luas Lingkaran (r={jari_jari}): {luas_lingkaran:.2f}")